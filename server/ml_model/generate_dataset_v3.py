def main(n_each: int = 7_500):
    out_dir = os.path.join(os.path.dirname(__file__), "datasets")
    os.makedirs(out_dir, exist_ok=True)

    records = []
    for _ in range(n_each):
        records.append(_maybe_flip(random.choice(GENERATORS_PII)()))
    for _ in range(n_each):
        records.append(_maybe_flip(random.choice(GENERATORS_NO_PII)()))
    random.shuffle(records)

    csv_path  = os.path.join(out_dir, "synthetic_kz_v3.csv")
    json_path = os.path.join(out_dir, "synthetic_kz_v3.json")

    df = pd.DataFrame(records)
    df.to_csv(csv_path, index=False, encoding="utf-8-sig",
              quoting=csv.QUOTE_NONNUMERIC)
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(records, f, ensure_ascii=False, indent=2)

    n_pii = sum(1 for r in records if r["label"] == 1)
    print(f"Датасет v3: {len(records)} записей  (с ПД: {n_pii}, без ПД: {len(records)-n_pii})")
    print(f"  CSV:  {csv_path}")
    print(f"  JSON: {json_path}")


if __name__ == "__main__":
    main()
